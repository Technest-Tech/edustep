function GuideBlock({
  icon: Icon,
  title,
  tone,
  children,
}: {
  icon: LucideIcon;
  title: string;
  tone: "teal" | "navy" | "warning";
  children: ReactNode;
}) {
  const styles = {
    teal: {
      shell: "border-teal/10 bg-mist/55",
      icon: "bg-white text-teal",
      title: "text-navy",
    },
    navy: {
      shell: "border-navy/[0.07] bg-cloud/60",
      icon: "bg-navy text-sun",
      title: "text-navy",
    },
    warning: {
      shell: "border-amber-200 bg-amber-50/80",
      icon: "bg-amber-100 text-amber-700",
      title: "text-amber-950",
    },
  }[tone];

  return (
    <div className={`flex gap-3 rounded-2xl border p-4 ${styles.shell}`}>
      <span
        className={`grid size-9 shrink-0 place-items-center rounded-xl ${styles.icon}`}
      >
        <Icon size={17} />
      </span>
      <div className="min-w-0">
        <p className={`text-xs font-black ${styles.title}`}>{title}</p>
        <div className="mt-1.5">{children}</div>
      </div>
    </div>
  );
}
