const guideById = new Map(guideSections.map((section) => [section.id, section]));
const guideGroups = groupDefinitions.map((group) => ({
  label: group.label,
  sections: group.ids
    .map((id) => guideById.get(id))
    .filter((section): section is GuideSection => Boolean(section)),
}));

export function DocsContent() {
  const { user } = useAuth();
  const workspaceHref = homeForRole(user?.role ?? "staff");
  const [query, setQuery] = useState("");
  const [activeSection, setActiveSection] = useState("introduction");

  const searchResults = useMemo(() => {
    const normalized = query.trim().toLowerCase();
    if (!normalized) return [];

    return guideSections.filter((section) => {
      const searchable = [
        section.title,
        section.summary,
        section.why,
        section.example,
        section.rule,
        ...section.steps.flatMap((step) => [step.title, step.body]),
        ...section.after,
        ...section.terms.flatMap(([term, definition]) => [term, definition]),
      ]
        .join(" ")
        .toLowerCase();

      return searchable.includes(normalized);
    });
  }, [query]);

  useEffect(() => {
    const nodes = Array.from(
      document.querySelectorAll<HTMLElement>("[data-doc-section]"),
    );
    const observer = new IntersectionObserver(
      (entries) => {
        const visible = entries
          .filter((entry) => entry.isIntersecting)
          .sort((a, b) => b.intersectionRatio - a.intersectionRatio)[0];

        if (visible?.target.id) setActiveSection(visible.target.id);
      },
      {
        rootMargin: "-18% 0px -68% 0px",
        threshold: [0.05, 0.2, 0.5],
      },
    );

    nodes.forEach((node) => observer.observe(node));
    return () => observer.disconnect();
  }, []);

  function jumpTo(id: string) {
    document.getElementById(id)?.scrollIntoView({
      behavior: "smooth",
      block: "start",
    });
    window.history.replaceState(null, "", `#${id}`);
  }

  return (
    <main className="mx-auto max-w-[1500px] px-4 py-7 sm:px-6 lg:px-8 lg:py-10">
      <div className="grid items-start gap-8 xl:grid-cols-[280px_minmax(0,930px)] 2xl:grid-cols-[280px_minmax(0,930px)_190px]">
        <aside className="sticky top-[94px] hidden max-h-[calc(100vh-118px)] overflow-y-auto pl-2 xl:block print:hidden">
          <SearchBox query={query} onChange={setQuery} />
          <GuideNavigation
            activeSection={activeSection}
            onSelect={jumpTo}
          />
        </aside>

        <article className="min-w-0">
          <DocsHero workspaceHref={workspaceHref} />

          <div className="mt-5 xl:hidden print:hidden">
            <SearchBox query={query} onChange={setQuery} />
            <label className="mt-3 block">
              <span className="sr-only">انتقل إلى قسم</span>
              <select
                value={activeSection}
                onChange={(event) => jumpTo(event.target.value)}
                className="min-h-12 w-full rounded-2xl border border-navy/[0.09] bg-white px-4 text-sm font-semibold text-navy outline-none focus:border-teal/40"
              >
                {guideGroups.map((group) => (
                  <optgroup key={group.label} label={group.label}>
                    {group.sections.map((section) => (
                      <option key={section.id} value={section.id}>
                        {section.title}
                      </option>
                    ))}
                  </optgroup>
                ))}
              </select>
            </label>
          </div>

          {query.trim() ? (
            <SearchResults
              query={query}
              results={searchResults}
              onSelect={jumpTo}
            />
          ) : null}

          <div className="mt-8 space-y-8 print:space-y-5">
            {guideSections.map((section, index) => (
              <GuideSectionCard
                key={section.id}
                section={section}
                index={index + 1}
              />
            ))}
          </div>
        </article>

        <aside className="sticky top-[94px] hidden 2xl:block print:hidden">
          <div className="rounded-2xl border border-navy/[0.07] bg-white p-4 shadow-[0_12px_30px_rgba(11,36,84,.04)]">
            <p className="text-xs font-bold text-navy">طريقة استخدام الدليل</p>
            <div className="mt-4 space-y-3">
              {[
                "افهم فايدة الشاشة",
                "اتبع الخطوات بالترتيب",
                "راجع نتيجة الحفظ",
                "ارجع للمصطلحات عند اللخبطة",
                "التزم بأهم قاعدة",
              ].map((item, index) => (
                <div key={item} className="flex items-start gap-2.5">
                  <span className="grid size-6 shrink-0 place-items-center rounded-lg bg-mist text-[10px] font-bold text-teal">
                    {index + 1}
                  </span>
                  <p className="pt-1 text-[11px] leading-5 text-slate">{item}</p>
                </div>
              ))}
            </div>
          </div>

          <div className="mt-4 rounded-2xl bg-navy p-4 text-white shadow-[0_16px_35px_rgba(11,36,84,.15)]">
            <Lightbulb size={18} className="text-sun" />
            <p className="mt-3 text-xs font-bold">مش عارف تبدأ منين؟</p>
            <p className="mt-2 text-[11px] leading-6 text-white/60">
              ابدأ بـ«رحلة العميل الكاملة»، وبعدها افتح شرح الشاشة التي تخص دورك.
            </p>
          </div>
        </aside>
      </div>
    </main>
  );
}

